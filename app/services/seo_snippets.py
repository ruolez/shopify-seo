SNIPPET_VERSION = "v5"


def generate_seo_snippet(include_website_schema=False, include_blogposting=False):
    """SEO fixes theme snippet. Defaults produce v5 — the schema-safe build.

    include_website_schema (v2 only): the WebSite JSON-LD block and its DOM-dedup
    script — retired because ai-seo-schema.liquid owns the canonical WebSite
    entity and the dedup script deleted arbitrary WebSite nodes at runtime.
    include_blogposting (v2/v3): the BlogPosting block — retired because it
    duplicated the theme's structured-data-article on default articles and
    collided with the NewsArticle emitted on article.news pages."""
    if include_website_schema:
        version = "v2"
        version_note = "  v2: synchronous dedup scripts, CSS font-display, twitter:image on blog listing."
    elif include_blogposting:
        version = "v3"
        version_note = "  v3: WebSite schema + dedup moved to ai-seo-schema.liquid (single schema source)."
    else:
        version = SNIPPET_VERSION
        version_note = ("  v4: BlogPosting removed — structured-data-article (blog) / seo-news-article (news) own article schema.\n"
                        "  v5: blog tag and paginated views noindexed, landing article noindexed, hub Blog + BreadcrumbList schema.")
    header = (
        "{% comment %} SEO Fixes Snippet "
        + version
        + " — auto-generated by SEO Platform.\n"
        "  Fixes: duplicate meta descriptions, font-display: swap,\n"
        "         Twitter meta tags, og:type for blog"
        + (", WebSite schema name" if include_website_schema else "")
        + ".\n" + version_note + "\n{% endcomment %}"
    )
    blogposting = _BLOGPOSTING_BLOCK if (include_blogposting or include_website_schema) else ""
    website = _WEBSITE_SCHEMA_BLOCK if include_website_schema else ""
    return header + blogposting + _SNIPPET_BODY + website


